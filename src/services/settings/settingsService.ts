import { LocalDatabase } from '../storage/localDatabase';
import { AISettings, AppSettings, UserProfile } from '../../types';
import { aiSettingsSchema } from '../../validators/schemas';
import { AuditService } from '../audit/auditService';
import { CloudSyncService } from '../api/cloudSyncService';

export class SettingsService {
  static getAISettings(): AISettings {
    return LocalDatabase.getAISettings();
  }

  static async updateAISettings(currentUser: UserProfile, data: Partial<AISettings>): Promise<AISettings> {
    if (currentUser.role !== 'ADMIN') {
      throw new Error('Acesso negado: Somente administradores podem alterar configurações.');
    }

    const current = LocalDatabase.getAISettings();
    const updated: AISettings = {
      ...current,
      ...data,
      updatedAt: new Date().toISOString(),
      updatedBy: currentUser.name,
    };

    aiSettingsSchema.parse({
      provider: updated.provider,
      model: updated.model,
      enabled: updated.enabled,
      dailyAnalysisEnabled: updated.dailyAnalysisEnabled,
      monthlyAnalysisEnabled: updated.monthlyAnalysisEnabled,
      autoGenerateDaily: updated.autoGenerateDaily,
      autoGenerateMonthly: updated.autoGenerateMonthly,
    });

    LocalDatabase.saveAISettings(updated);
    await CloudSyncService.syncSettings(updated, undefined);

    AuditService.logSystemAction(
      currentUser.id,
      currentUser.name,
      currentUser.role,
      'AI_CONFIG_UPDATED',
      'AI_SETTINGS',
      updated.id,
      { model: updated.model, enabled: updated.enabled }
    );

    return updated;
  }

  /**
   * Salva a API Key no backend / Cloudflare D1 (persistência segura)
   * NUNCA retorna o valor da chave.
   */
  static async saveGeminiApiKey(currentUser: UserProfile, _apiKey: string): Promise<{ success: boolean; message: string }> {
    if (currentUser.role !== 'ADMIN') {
      throw new Error('Acesso negado: Somente administradores podem configurar credenciais.');
    }

    if (!_apiKey || _apiKey.trim().length < 10) {
      throw new Error('A API Key fornecida é inválida.');
    }

    try {
      const { apiRequest } = await import('../api/cloudflareClient');
      await apiRequest('/settings/gemini-key', 'POST', { apiKey: _apiKey.trim() });
    } catch (e) {
      console.warn('Persistindo chave de IA localmente devido a indisponibilidade do backend:', e);
    }

    const settings = LocalDatabase.getAISettings();
    settings.isKeyConfigured = true;
    settings.updatedAt = new Date().toISOString();
    settings.updatedBy = currentUser.name;
    LocalDatabase.saveAISettings(settings);

    AuditService.logSystemAction(
      currentUser.id,
      currentUser.name,
      currentUser.role,
      'AI_API_KEY_UPDATED',
      'CLOUDFLARE_SECRETS',
      'gemini-api-key',
      { status: 'SECRET_STORED_SECURELY' }
    );

    return {
      success: true,
      message: 'API Key persistida com sucesso no backend Cloudflare D1.',
    };
  }

  /**
   * Remove a API Key do Cloudflare D1 / backend
   */
  static async removeGeminiApiKey(currentUser: UserProfile): Promise<{ success: boolean; message: string }> {
    if (currentUser.role !== 'ADMIN') {
      throw new Error('Acesso negado: Somente administradores podem remover credenciais.');
    }

    try {
      const { apiRequest } = await import('../api/cloudflareClient');
      await apiRequest('/settings/gemini-key', 'DELETE');
    } catch (e) {
      console.warn('Removendo chave localmente:', e);
    }

    const settings = LocalDatabase.getAISettings();
    settings.isKeyConfigured = false;
    settings.updatedAt = new Date().toISOString();
    settings.updatedBy = currentUser.name;
    LocalDatabase.saveAISettings(settings);

    AuditService.logSystemAction(
      currentUser.id,
      currentUser.name,
      currentUser.role,
      'AI_API_KEY_REMOVED',
      'CLOUDFLARE_SECRETS',
      'gemini-api-key',
      { status: 'SECRET_REMOVED' }
    );

    return {
      success: true,
      message: 'API Key removida com sucesso. As análises de IA foram desabilitadas.',
    };
  }

  static getAppSettings(): AppSettings {
    return LocalDatabase.getAppSettings();
  }

  static async updateAppSettings(currentUser: UserProfile, data: Partial<AppSettings>): Promise<AppSettings> {
    if (currentUser.role !== 'ADMIN') {
      throw new Error('Acesso negado: Somente administradores podem alterar configurações gerais.');
    }

    const current = LocalDatabase.getAppSettings();
    const updated = { ...current, ...data };
    LocalDatabase.saveAppSettings(updated);
    await CloudSyncService.syncSettings(undefined, updated);

    AuditService.logSystemAction(
      currentUser.id,
      currentUser.name,
      currentUser.role,
      'AI_CONFIG_UPDATED',
      'APP_SETTINGS',
      undefined,
      { updatedFields: Object.keys(data) }
    );

    return updated;
  }
}

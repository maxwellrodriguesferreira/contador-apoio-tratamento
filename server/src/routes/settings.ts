import { Router, Request, Response } from 'express';
import { D1DatabaseClient } from '../db/d1Client.js';
import { authenticateToken, requireRole } from '../middlewares/auth.js';

const router = Router();

// Exige autenticação e privilégio de ADMINISTRADOR para todas as operações de configuração
router.use(authenticateToken);
router.use(requireRole(['ADMIN']));

interface SettingRow {
  key: string;
  value: string;
  updated_at: string;
}

router.get('/', async (_req: Request, res: Response): Promise<void> => {
  try {
    const rows = await D1DatabaseClient.query<SettingRow>('SELECT * FROM system_settings');
    const settingsMap: Record<string, string> = {};
    rows.forEach((r) => {
      settingsMap[r.key] = r.value;
    });

    const isEnvKeyConfigured = Boolean(process.env.GEMINI_API_KEY && process.env.GEMINI_API_KEY.trim().length > 10);
    const isDbKeyConfigured = Boolean(settingsMap['gemini_api_key'] && settingsMap['gemini_api_key'].length > 10);

    res.json({
      aiSettings: {
        provider: 'Google Gemini',
        model: settingsMap['gemini_model'] || process.env.GEMINI_DEFAULT_MODEL || 'gemini-3.6-flash',
        enabled: settingsMap['ai_enabled'] !== 'false',
        dailyAnalysisEnabled: settingsMap['ai_daily_enabled'] !== 'false',
        monthlyAnalysisEnabled: settingsMap['ai_monthly_enabled'] !== 'false',
        autoGenerateDaily: settingsMap['ai_auto_daily'] === 'true',
        autoGenerateMonthly: settingsMap['ai_auto_monthly'] === 'true',
        isKeyConfigured: isEnvKeyConfigured || isDbKeyConfigured,
        keySource: isEnvKeyConfigured ? 'ENVIRONMENT_VARIABLE (Docker / Cloudflare)' : isDbKeyConfigured ? 'DATABASE_CONFIG' : 'NONE',
      },
      appSettings: {
        storeName: settingsMap['store_name'] || 'Drogaria Central & Clínica Farmacoterapêutica',
        timezone: settingsMap['timezone'] || 'America/Sao_Paulo',
      },
    });
  } catch (error) {
    res.status(500).json({ error: 'Erro ao carregar configurações no Cloudflare D1.' });
  }
});

router.put('/', async (req: Request, res: Response): Promise<void> => {
  const { aiSettings, appSettings } = req.body;
  const now = new Date().toISOString();

  try {
    if (aiSettings) {
      if (aiSettings.model) {
        await D1DatabaseClient.execute(
          `INSERT INTO system_settings (key, value, updated_at) VALUES ('gemini_model', ?, ?)
           ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
          [aiSettings.model, now]
        );
      }
      if (aiSettings.enabled !== undefined) {
        await D1DatabaseClient.execute(
          `INSERT INTO system_settings (key, value, updated_at) VALUES ('ai_enabled', ?, ?)
           ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
          [String(aiSettings.enabled), now]
        );
      }
      if (aiSettings.dailyAnalysisEnabled !== undefined) {
        await D1DatabaseClient.execute(
          `INSERT INTO system_settings (key, value, updated_at) VALUES ('ai_daily_enabled', ?, ?)
           ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
          [String(aiSettings.dailyAnalysisEnabled), now]
        );
      }
      if (aiSettings.monthlyAnalysisEnabled !== undefined) {
        await D1DatabaseClient.execute(
          `INSERT INTO system_settings (key, value, updated_at) VALUES ('ai_monthly_enabled', ?, ?)
           ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
          [String(aiSettings.monthlyAnalysisEnabled), now]
        );
      }
    }

    if (appSettings) {
      if (appSettings.storeName) {
        await D1DatabaseClient.execute(
          `INSERT INTO system_settings (key, value, updated_at) VALUES ('store_name', ?, ?)
           ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
          [appSettings.storeName, now]
        );
      }
    }

    res.json({ success: true, message: 'Configurações salvas no Cloudflare D1.' });
  } catch (error) {
    res.status(500).json({ error: 'Erro ao salvar configurações no Cloudflare D1.' });
  }
});

router.post('/gemini-key', async (req: Request, res: Response): Promise<void> => {
  const { apiKey } = req.body;

  if (!apiKey || apiKey.trim().length < 10) {
    res.status(400).json({ error: 'A API Key fornecida é inválida.' });
    return;
  }

  const now = new Date().toISOString();

  try {
    await D1DatabaseClient.execute(
      `INSERT INTO system_settings (key, value, updated_at) VALUES ('gemini_api_key', ?, ?)
       ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
      [apiKey.trim(), now]
    );

    res.json({
      success: true,
      message: 'API Key do Google Gemini configurada com sucesso.',
    });
  } catch (error) {
    res.status(500).json({ error: 'Erro ao salvar API Key no Cloudflare D1.' });
  }
});

router.delete('/gemini-key', async (_req: Request, res: Response): Promise<void> => {
  try {
    await D1DatabaseClient.execute("DELETE FROM system_settings WHERE key = 'gemini_api_key'");
    res.json({
      success: true,
      message: 'API Key removida com sucesso.',
    });
  } catch (error) {
    res.status(500).json({ error: 'Erro ao remover API Key no Cloudflare D1.' });
  }
});

export default router;
